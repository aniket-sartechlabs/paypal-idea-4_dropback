"""PayPal Orders v2 and Payments v2 through the APIMatic-generated PayPal Server SDK.

`paypal-server-sdk` (package `paypalserversdk`) is generated by APIMatic from PayPal's
OpenAPI definitions. DropBack builds requests with the SDK's typed models
(`OrderRequest`, `PurchaseUnitRequest`, `RefundRequest`, `Money`, ...) and lets the SDK
manage OAuth client-credential tokens. The SDK is synchronous, so each call runs in a
worker thread to keep FastAPI's event loop free.

Webhook signature verification (`/v1/notifications/verify-webhook-signature`) is not
part of the Server SDK, so that one call uses httpx with an SDK-issued access token.
"""

import asyncio
import json
import logging
from typing import Any, Callable

import httpx
from paypalserversdk.configuration import Environment
from paypalserversdk.exceptions.api_exception import ApiException
from paypalserversdk.exceptions.error_exception import ErrorException
from paypalserversdk.http.auth.o_auth_2 import ClientCredentialsAuthCredentials
from paypalserversdk.models.amount_breakdown import AmountBreakdown
from paypalserversdk.models.amount_with_breakdown import AmountWithBreakdown
from paypalserversdk.models.checkout_payment_intent import CheckoutPaymentIntent
from paypalserversdk.models.item import Item
from paypalserversdk.models.item_category import ItemCategory
from paypalserversdk.models.money import Money
from paypalserversdk.models.order_application_context import OrderApplicationContext
from paypalserversdk.models.order_application_context_landing_page import OrderApplicationContextLandingPage
from paypalserversdk.models.order_application_context_user_action import OrderApplicationContextUserAction
from paypalserversdk.models.order_request import OrderRequest
from paypalserversdk.models.purchase_unit_request import PurchaseUnitRequest
from paypalserversdk.models.refund_request import RefundRequest
from paypalserversdk.paypal_serversdk_client import PaypalServersdkClient

from app.config import get_settings

log = logging.getLogger("dropback.paypal")


class PayPalError(RuntimeError):
    """A PayPal call failed.

    `retryable` is True when PayPal could not be reached or returned a 5xx, so the
    outcome is unknown and a retry must reuse the same PayPal-Request-Id. A 4xx
    rejection is final for that request.
    """

    def __init__(self, message: str, status_code: int = 502, detail: Any = None, retryable: bool = False):
        super().__init__(message)
        self.status_code = status_code
        self.detail = detail
        self.retryable = retryable


class PayPalClient:
    def __init__(self) -> None:
        self.settings = get_settings()
        self._client: PaypalServersdkClient | None = None
        self._client_key: tuple[str, str, str] | None = None

    # -- configuration -------------------------------------------------------
    def _ensure_configured(self) -> None:
        if not self.settings.paypal_ready:
            raise PayPalError("PayPal is not configured. Set PAYPAL_CLIENT_ID and PAYPAL_CLIENT_SECRET.", 503)
        sandbox_url = "sandbox" in self.settings.paypal_base_url.lower()
        if self.settings.is_production and sandbox_url and self.settings.paypal_env.lower() != "sandbox":
            raise PayPalError("PAYPAL_ENV is live but PAYPAL_BASE_URL points at the sandbox.", 503)
        if not self.settings.is_production and not sandbox_url:
            raise PayPalError("Development checkout is restricted to the PayPal sandbox.", 503)

    @property
    def environment(self) -> Environment:
        return Environment.SANDBOX if self.settings.paypal_env.lower() == "sandbox" else Environment.PRODUCTION

    def sdk(self) -> PaypalServersdkClient:
        self._ensure_configured()
        key = (self.settings.paypal_client_id, self.settings.paypal_client_secret, self.settings.paypal_env.lower())
        if self._client is None or self._client_key != key:
            self._client = PaypalServersdkClient(
                client_credentials_auth_credentials=ClientCredentialsAuthCredentials(
                    o_auth_client_id=self.settings.paypal_client_id,
                    o_auth_client_secret=self.settings.paypal_client_secret,
                ),
                environment=self.environment,
                timeout=30,
                max_retries=0,  # DropBack retries explicitly with the same PayPal-Request-Id.
            )
            self._client_key = key
        return self._client

    # -- call helpers ----------------------------------------------------------
    async def _call(self, operation: str, fn: Callable[[], Any]) -> dict:
        try:
            response = await asyncio.to_thread(fn)
        except ErrorException as exc:
            code = int(getattr(exc, "response_code", 502) or 502)
            detail = {"name": getattr(exc, "name", None), "message": getattr(exc, "message", None), "debug_id": getattr(exc, "debug_id", None)}
            log.warning("PayPal %s rejected (%s): %s", operation, code, detail)
            message = detail["message"] or "PayPal rejected the request."
            raise PayPalError(f"PayPal {operation} failed: {message}", 502, detail, retryable=code >= 500) from exc
        except ApiException as exc:
            code = int(getattr(exc, "response_code", 502) or 502)
            log.warning("PayPal %s failed with HTTP %s", operation, code)
            raise PayPalError(f"PayPal {operation} failed (HTTP {code}).", 502, {"status_code": code}, retryable=code >= 500) from exc
        except PayPalError:
            raise
        except Exception as exc:  # network errors from the SDK's HTTP client
            log.warning("PayPal %s could not be reached: %s", operation, exc)
            raise PayPalError("PayPal could not be reached. Retry this operation in a moment.", 502, retryable=True) from exc
        text = getattr(response, "text", "") or ""
        return json.loads(text) if text.strip() else {}

    # -- Orders v2 --------------------------------------------------------------
    async def create_order(self, order_id: str, request_id: str, items: list[dict], total: str, currency: str, brand: str) -> dict:
        sdk = self.sdk()
        body = OrderRequest(
            intent=CheckoutPaymentIntent.CAPTURE,
            purchase_units=[PurchaseUnitRequest(
                reference_id=order_id,
                description=f"{brand} order {order_id[:8]}",
                amount=AmountWithBreakdown(
                    currency_code=currency,
                    value=total,
                    breakdown=AmountBreakdown(item_total=Money(currency_code=currency, value=total)),
                ),
                items=[Item(
                    name=item["name"][:127],
                    sku=item["sku"][:127],
                    unit_amount=Money(currency_code=currency, value=item["unit_price"]),
                    quantity=str(item["quantity"]),
                    category=ItemCategory.PHYSICAL_GOODS,
                ) for item in items],
            )],
            application_context=OrderApplicationContext(
                brand_name=brand[:127],
                landing_page=OrderApplicationContextLandingPage.NO_PREFERENCE,
                user_action=OrderApplicationContextUserAction.PAY_NOW,
                return_url=f"{self.settings.app_base_url.rstrip('/')}/checkout/return",
                cancel_url=f"{self.settings.app_base_url.rstrip('/')}/checkout/cancel",
            ),
        )
        return await self._call("create order", lambda: sdk.orders.create_order({
            "body": body, "paypal_request_id": request_id, "prefer": "return=representation",
        }))

    async def get_order(self, paypal_order_id: str) -> dict:
        sdk = self.sdk()
        return await self._call("get order", lambda: sdk.orders.get_order({"id": paypal_order_id}))

    async def capture_order(self, paypal_order_id: str, request_id: str) -> dict:
        sdk = self.sdk()
        return await self._call("capture order", lambda: sdk.orders.capture_order({
            "id": paypal_order_id, "paypal_request_id": request_id, "prefer": "return=representation",
        }))

    # -- Payments v2 ------------------------------------------------------------
    async def get_capture(self, paypal_capture_id: str) -> dict:
        sdk = self.sdk()
        return await self._call("get capture", lambda: sdk.payments.get_captured_payment({"capture_id": paypal_capture_id}))

    async def refund_capture(self, paypal_capture_id: str, request_id: str, amount: str, currency: str, note: str) -> dict:
        sdk = self.sdk()
        body = RefundRequest(amount=Money(currency_code=currency, value=amount), note_to_payer=note[:255])
        return await self._call("refund", lambda: sdk.payments.refund_captured_payment({
            "capture_id": paypal_capture_id, "paypal_request_id": request_id, "prefer": "return=representation", "body": body,
        }))

    async def get_refund(self, paypal_refund_id: str) -> dict:
        sdk = self.sdk()
        return await self._call("get refund", lambda: sdk.payments.get_refund({"refund_id": paypal_refund_id}))

    # -- OAuth / webhooks -------------------------------------------------------
    async def access_token(self) -> str:
        sdk = self.sdk()
        try:
            token = await asyncio.to_thread(sdk.oauth_2.fetch_token)
        except Exception as exc:
            raise PayPalError("PayPal authentication failed.", 502, retryable=True) from exc
        access = getattr(token, "access_token", None)
        if not access:
            raise PayPalError("PayPal authentication failed.", 502)
        return access

    async def verify_webhook(self, headers: dict[str, str], event: dict) -> bool:
        if not self.settings.paypal_webhook_id:
            return False
        token = await self.access_token()
        verification = {
            "auth_algo": headers.get("paypal-auth-algo", ""),
            "cert_url": headers.get("paypal-cert-url", ""),
            "transmission_id": headers.get("paypal-transmission-id", ""),
            "transmission_sig": headers.get("paypal-transmission-sig", ""),
            "transmission_time": headers.get("paypal-transmission-time", ""),
            "webhook_id": self.settings.paypal_webhook_id,
            "webhook_event": event,
        }
        async with httpx.AsyncClient(timeout=20) as client:
            try:
                response = await client.post(
                    f"{self.settings.paypal_base_url.rstrip('/')}/v1/notifications/verify-webhook-signature",
                    headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
                    json=verification,
                )
            except httpx.HTTPError as exc:
                raise PayPalError("PayPal webhook verification could not be reached.", retryable=True) from exc
        if response.is_error:
            raise PayPalError("PayPal webhook verification failed.", 502)
        return response.json().get("verification_status") == "SUCCESS"


paypal = PayPalClient()
